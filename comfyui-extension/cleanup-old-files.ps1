<#
.SYNOPSIS
  Safety net for Comfy: deletes old files ComfyUI left in output, temp and input\comfy.

.DESCRIPTION
  Comfy asks ComfyUI to delete each job's files through the job_cleanup extension. This script
  catches what that missed (extension not installed, a crash, a job that failed before storing).
  It deletes regular files whose last write is older than -Days, under <ComfyRoot>\output,
  <ComfyRoot>\temp and <ComfyRoot>\input\comfy only. It never follows junctions or symlinks,
  never deletes directories, and logs counts only.

  WARNING: this includes anything you generated by hand in the ComfyUI browser UI that is still in
  output. Only run it where ComfyUI output is meant to be disposable (Comfy stores what it keeps).

.PARAMETER ComfyRoot  The ComfyUI folder (the one that contains output, temp and input).
.PARAMETER Days       Delete files older than this many days. Default 2.
.PARAMETER WhatIf     Show what would be deleted without deleting.
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
  [Parameter(Mandatory = $true)][string]$ComfyRoot,
  [ValidateRange(1, 3650)][int]$Days = 2
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path -LiteralPath $ComfyRoot).Path
$cutoff = (Get-Date).AddDays(-$Days)
$deleted = 0
$failed = 0

function Remove-OldFiles([string]$Folder) {
  if (-not (Test-Path -LiteralPath $Folder -PathType Container)) { return }
  foreach ($item in Get-ChildItem -LiteralPath $Folder -Force) {
    if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { continue }
    if ($item.PSIsContainer) { Remove-OldFiles $item.FullName; continue }
    if ($item.LastWriteTime -ge $cutoff) { continue }
    if ($PSCmdlet.ShouldProcess($item.FullName, 'Delete')) {
      try { Remove-Item -LiteralPath $item.FullName -Force; $script:deleted++ }
      catch { $script:failed++ }
    } else {
      $script:deleted++
    }
  }
}

foreach ($sub in @('output', 'temp', 'input\comfy')) { Remove-OldFiles (Join-Path $root $sub) }

$verb = if ($WhatIfPreference) { 'would delete' } else { 'deleted' }
Write-Output ("{0} job cleanup: {1} {2} file(s) older than {3} day(s), {4} failed" -f (Get-Date -Format s), $verb, $deleted, $Days, $failed)
